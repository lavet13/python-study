import pandas as pd

# Загружаем датасет из CSV-файла.
# delimiter="," — разделитель столбцов запятая (стандарт для этого файла).
# Результат — объект DataFrame: таблица с именованными столбцами и индексом строк.
df = pd.read_csv("learn_dataset.csv", delimiter=",")

# info() — "рентген" датасета: показывает имя каждого столбца,
# тип данных (int64 = целое число, str = строка) и количество непустых значений.
# Если Non-Null Count < общего числа строк — в столбце есть пропуски (NaN).
print("--------Общая информация--------")
df.info()

# shape возвращает кортеж (количество_строк, количество_столбцов).
# Позволяет быстро оценить масштаб датасета без вывода всей таблицы.
print(f"\nРазмерность датасета: {df.shape}")

# head(n) возвращает первые n строк (по умолчанию 5).
# Используется для быстрой визуальной проверки структуры и содержимого данных.
print("\n--- Первые 5 строк таблицы ---")
print(df.head())

# columns.tolist() возвращает список имён всех столбцов в виде Python-списка.
# Удобно для программной работы с именами признаков.
print("\n--- Список признаков ---")
print(df.columns.tolist())

# tail(n) возвращает последние n строк (по умолчанию 5).
# Помогает убедиться, что конец файла загружен корректно и нет артефактов.
print("\n--- Последние 5 строк таблицы ---")
print(df.tail())

# describe() — сводная статистика по числовым столбцам.
# count  — количество непустых значений
# mean   — среднее значение
# std    — стандартное отклонение: насколько значения разбросаны вокруг среднего.
#          Большое std = высокий разброс, малое std = значения кучкуются у среднего.
# min    — минимальное значение в столбце
# 25%    — первый квартиль: 25% всех значений ниже этой отметки
# 50%    — медиана: ровно половина значений ниже, половина выше.
#          Устойчивее к выбросам, чем среднее.
# 75%    — третий квартиль: 75% всех значений ниже этой отметки
# max    — максимальное значение в столбце
# Наблюдение: capitalgain и capitalloss — медиана и 75% равны 0,
# mean близко к 0. Это признак сильной правосторонней скошенности:
# подавляющее большинство людей не имеют капитальных доходов/убытков.
print("\n--- Описательные статистики (числовые) ---")
print(df.describe())

# describe(include='str') — аналогичная сводка для строковых (категориальных) столбцов.
# count  — количество непустых значений
# unique — сколько различных значений встречается в столбце
# top    — значение, которое встречается чаще всего (мода)
# freq   — сколько раз это значение встречается в датасете
print("\n--- Описательные статистики (категориальные) ---")
print(df.describe(include="str"))
