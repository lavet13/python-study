import pandas as pd

df = pd.read_csv("learn_dataset.csv", delimiter=",")

# ── 1. Обнаружение скрытых пропусков ─────────────────────────────────────────
# В датасете нет явных NaN, но три столбца содержат значение '?',
# которое кодирует отсутствующие данные.
print("--- Количество '?' по столбцам ---")
for col in ["workclass", "occupation", "native-country"]:
    count = (df[col] == "?").sum()
    print(f"  {col}: {count}")

# replace() заменяет все вхождения '?' на pd.NA (официальный тип пропуска).
# После этого info() покажет реальное число непустых значений.
df_with_na = df.replace("?", pd.NA)
print("\n--- После замены '?' на NaN ---")
df_with_na.info()

# ── 2. Удаление строк с пропусками (dropna) ───────────────────────────────────
# dropna() удаляет все строки, где есть хотя бы один NaN.
# Работаем с копией, чтобы не трогать исходный датасет.
df_dropped = df_with_na.dropna()
print(f"\n--- После dropna(): осталось строк: {len(df_dropped)} из {len(df)} ---")

# ── 3. Заполнение нулями (fillna с константой) ────────────────────────────────
# fillna(0) заменяет все NaN нулём. Для числовых признаков это иногда уместно,
# но для категориальных — нет: '0' не является осмысленным значением пола.
df_zero = df_with_na.fillna(0)
print(f"\n--- После fillna(0): пропусков осталось: {df_zero.isnull().sum().sum()} ---")

# ── 4. Правильный способ: заполнение модой для категориальных признаков ────────
# Для категориальных столбцов среднее и медиана не применимы.
# Правильная стратегия — заполнять самым частым значением (модой).
# mode() возвращает Series; [0] берёт первый (самый частый) элемент.
df_filled = df_with_na.copy()
for col in ["workclass", "occupation", "native-country"]:
    most_frequent = str(df_filled[col].mode()[0])
    df_filled[col] = df_filled[col].fillna(most_frequent)
    print(f"  {col}: пропуски заполнены значением '{most_frequent}'")

print(
    f"\n--- После заполнения модой: пропусков осталось: {df_filled.isnull().sum().sum()} ---"
)
df_filled.info()
